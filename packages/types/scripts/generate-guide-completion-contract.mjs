import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const artifactPath = path.join(root, 'contracts', 'guide-completion-v1.openapi.json');
const outputPath = path.join(root, 'src', 'guide-completion.generated.ts');
const artifactBytes = await readFile(artifactPath);
const contract = JSON.parse(artifactBytes.toString('utf8'));
const schemas = contract.components.schemas;
const version = schemas.GuideCompletionRequest.properties.contract_version.const;
const errorCodes = schemas.GuideCompletionError.properties.code.enum;
const eventTypes = schemas.GuideCompletionEvent.oneOf.map((entry) => {
  const schemaName = entry.$ref.split('/').at(-1);
  return schemas[schemaName].properties.type.const;
});
const digest = createHash('sha256').update(artifactBytes).digest('hex');
const quoted = (value) => `  '${value}',`;
const output = [
  '/* Generated by scripts/generate-guide-completion-contract.mjs. Do not edit. */',
  `export const GUIDE_COMPLETION_CONTRACT_VERSION = '${version}' as const;`,
  `export const GUIDE_COMPLETION_ARTIFACT_SHA256 = '${digest}' as const;`,
  'export const GUIDE_COMPLETION_ERROR_CODES = [',
  ...errorCodes.map(quoted),
  '] as const;',
  'export const GUIDE_COMPLETION_EVENT_TYPES = [',
  ...eventTypes.map(quoted),
  '] as const;',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8');
  if (current !== output) {
    process.stderr.write('Generated Guide completion contract is stale.\n');
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, output);
}
