import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { registerHooks } from 'node:module';
import path from 'node:path';

registerHooks({
  resolve(specifier, context, nextResolve) {
    if (/^\.{1,2}\//.test(specifier) && !path.extname(specifier)) {
      return nextResolve(`${specifier}.ts`, context);
    }
    return nextResolve(specifier, context);
  },
});

const { canonicalAgentJson } = await import('../src/agent-runtime.ts');

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const artifactPath = path.join(root, 'contracts', 'governance-api-v1.openapi.json');
const pinnedHashPath = path.join(root, 'contracts', 'governance-api-v1.HASH');
const pinnedVersionPath = path.join(root, 'contracts', 'governance-api-v1.VERSION');
const outputPath = path.join(root, 'src', 'governance-api.generated.ts');

const [artifactBytes, pinnedHashText, pinnedVersionText] = await Promise.all([
  readFile(artifactPath, 'utf8'),
  readFile(pinnedHashPath, 'utf8'),
  readFile(pinnedVersionPath, 'utf8'),
]);

const document = JSON.parse(artifactBytes);
const pinnedHash = pinnedHashText.trim();
const pinnedVersion = pinnedVersionText.trim();

// The digest is recomputed from the artifact using the same RFC 8785
// canonicalization nona_server applies (src/research/common/canonical.py).
// Copying the server's digest would make the gate vacuous: a stale artifact
// shipped alongside its own stale hash would still agree with itself.
const computedHash = `sha256:${createHash('sha256')
  .update(canonicalAgentJson(document), 'utf8')
  .digest('hex')}`;

if (computedHash !== pinnedHash) {
  process.stderr.write(
    'Governance API artifact does not match the pinned nona_server digest.\n'
      + `  pinned   (contracts/governance-api-v1.HASH): ${pinnedHash}\n`
      + `  computed (contracts/governance-api-v1.openapi.json): ${computedHash}\n`
      + 'Re-vendor both files from the same nona_server contract build.\n',
  );
  process.exit(1);
}

const artifactVersion = document.info.version;
if (artifactVersion !== pinnedVersion) {
  process.stderr.write(
    'Governance API artifact version does not match the pinned version.\n'
      + `  pinned   (contracts/governance-api-v1.VERSION): ${pinnedVersion}\n`
      + `  artifact (info.version): ${artifactVersion}\n`,
  );
  process.exit(1);
}

const endpoints = [];
for (const [routePath, pathItem] of Object.entries(document.paths).sort(
  ([left], [right]) => (left < right ? -1 : left > right ? 1 : 0),
)) {
  for (const [method, operation] of Object.entries(pathItem).sort(
    ([left], [right]) => (left < right ? -1 : left > right ? 1 : 0),
  )) {
    endpoints.push({
      operationId: operation.operationId,
      method: method.toUpperCase(),
      path: routePath,
    });
  }
}

const schemaNames = Object.keys(document.components.schemas).sort();

const output = [
  '/* Generated by scripts/generate-governance-api-contract.mjs. Do not edit. */',
  `export const GOVERNANCE_API_VERSION = '${pinnedVersion}' as const;`,
  `export const GOVERNANCE_API_HASH = '${pinnedHash}' as const;`,
  'export const GOVERNANCE_API_ENDPOINTS = [',
  ...endpoints.map(
    (endpoint) =>
      `  { operationId: '${endpoint.operationId}', method: '${endpoint.method}', path: '${endpoint.path}' },`,
  ),
  '] as const;',
  `export const GOVERNANCE_API_ENDPOINT_COUNT = ${endpoints.length} as const;`,
  'export const GOVERNANCE_API_SCHEMA_NAMES = [',
  ...schemaNames.map((name) => `  '${name}',`),
  '] as const;',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => null);
  if (current !== output) {
    process.stderr.write('Generated governance API contract is stale.\n');
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, output);
}
