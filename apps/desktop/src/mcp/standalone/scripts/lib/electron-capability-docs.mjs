function escapeCell(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function codeList(values) {
  return values.length === 0 ? '--' : values.map((value) => `\`${value}\``).join(', ');
}

export function renderElectronCapabilityMatrix(manifest) {
  const capabilities = [...manifest.capabilities].sort((left, right) => (
    left.domain.localeCompare(right.domain) || left.id.localeCompare(right.id)
  ));
  const uniqueIpcChannels = new Set(capabilities.flatMap(({ ipcChannels }) => ipcChannels));
  const preloadMethods = capabilities.flatMap(({ preloadMethods }) => preloadMethods);
  const currentTools = new Set(capabilities.flatMap(({ mcpTools }) => mcpTools));
  const targetTools = new Set(capabilities.flatMap(({ targetMcpTools = [] }) => targetMcpTools));
  const classificationCounts = new Map();
  for (const capability of capabilities) {
    classificationCounts.set(
      capability.classification,
      (classificationCounts.get(capability.classification) ?? 0) + 1,
    );
  }

  const lines = [
    '---',
    'id: TICKET_1235_CAPABILITY_MATRIX',
    'title: "Generated Electron-to-MCP capability parity matrix"',
    'status: GENERATED',
    'created: 2026-07-26',
    'feature_group: mcp-interface',
    '---',
    '',
    '# Generated Electron-to-MCP Capability Matrix',
    '',
    '> Generated from',
    '> `apps/desktop/src/mcp/standalone/src/electron-capability-manifest.json`.',
    '> Do not edit this file manually. Run `npm run generate:capability-matrix`',
    '> from the standalone MCP package after ratifying manifest changes.',
    '',
    '## Current Source-Derived Summary',
    '',
    '| Measure | Count |',
    '|---|---:|',
    `| Stable business capability rows | ${capabilities.length} |`,
    `| Classified preload methods | ${preloadMethods.length} |`,
    `| Classified unique IPC channels | ${uniqueIpcChannels.size} |`,
    `| Typed MCP tools referenced by covered rows | ${currentTools.size} |`,
    `| Ratified target MCP tools not yet registered | ${targetTools.size} |`,
    '',
    '| Classification | Capability rows |',
    '|---|---:|',
    ...[...classificationCounts.entries()]
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([classification, count]) => `| \`${classification}\` | ${count} |`),
    '',
    'The standalone registry total is intentionally not encoded here as a',
    'permanent constant. The parity test derives it from `registerAllTools()`',
    'source on every run; infrastructure-only MCP tools need not map to an',
    'Electron user capability.',
    '',
    '## Capability Rows',
    '',
    '| ID | Domain | Capability | Classification | Ownership | Auth | Preload | IPC | Current typed tools | Ratified target tools | Owning sources |',
    '|---|---|---|---|---|---|---:|---:|---|---|---|',
    ...capabilities.map((capability) => `${[
      `| \`${escapeCell(capability.id)}\``,
      escapeCell(capability.domain),
      escapeCell(capability.name),
      `\`${capability.classification}\``,
      `\`${capability.ownership}\``,
      codeList(capability.authTiers),
      capability.preloadMethods.length,
      capability.ipcChannels.length,
      codeList(capability.mcpTools),
      codeList(capability.targetMcpTools ?? []),
      codeList(capability.owningSources),
    ].join(' | ')} |`),
    '',
    '## Mixed Class-S / Class-R Ownership Splits',
    '',
    '| ID | Owning split |',
    '|---|---|',
    ...capabilities
      .filter(({ ownership }) => ownership === 'mixed')
      .map((capability) => (
        `| \`${capability.id}\` | ${escapeCell(capability.ownershipNotes)} |`
      )),
    '',
    '## Reviewed Exclusions and Lower Layers',
    '',
    '| ID | Classification | Rationale |',
    '|---|---|---|',
    ...capabilities
      .filter(({ rationale }) => Boolean(rationale))
      .map((capability) => (
        `| \`${capability.id}\` | \`${capability.classification}\` | ${escapeCell(capability.rationale)} |`
      )),
    '',
  ];

  return `${lines.join('\n')}\n`;
}
